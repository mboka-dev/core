#!/usr/bin/env node
// Ships data/ inside each package. Never edit the copies by hand.
//   - Python: JSON files copied to packages/py/src/mboka/data/
//   - JS:     a typed module generated at packages/js/src/generated/data.ts
//
//   node scripts/sync-data.mjs           # write copies
//   node scripts/sync-data.mjs --check   # fail if copies are stale (used in CI)

import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'data');
const pyTarget = join(root, 'packages/py/src/mboka/data');
const jsTarget = join(root, 'packages/js/src/generated/data.ts');
const check = process.argv.includes('--check');

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (name === 'schema' || name === '__pycache__') return [];
    return statSync(path).isDirectory() ? listFiles(path) : name.endsWith('.json') ? [path] : [];
  });
}

// Expected outputs, keyed by absolute path.
const expected = new Map();
const sourceFiles = listFiles(src).map((f) => relative(src, f)).sort();

for (const f of sourceFiles) expected.set(join(pyTarget, f), readFileSync(join(src, f), 'utf8'));

const types = {
  departements: 'DepartementsFile',
  communes: 'CommunesFile',
  arrondissements: 'ArrondissementsFile',
  numerotation: 'NumerotationFile',
};
let ts = '// AUTO-GENERATED by scripts/sync-data.mjs from /data. Do not edit: change /data and run `npm run sync`.\n';
ts += `import type { ${Object.values(types).join(', ')} } from '../types.js';\n`;
for (const f of sourceFiles) {
  const name = basename(f, '.json');
  if (!types[name]) throw new Error(`No TypeScript type mapped for data file ${f}; add it in scripts/sync-data.mjs`);
  const { $schema, ...content } = JSON.parse(readFileSync(join(src, f), 'utf8'));
  ts += `\nexport const ${name}: ${types[name]} = ${JSON.stringify(content, null, 2)};\n`;
}
expected.set(jsTarget, ts);

if (check) {
  const actualPy = listFiles(pyTarget).sort();
  const expectedPy = [...expected.keys()].filter((p) => p.startsWith(pyTarget)).sort();
  let stale = JSON.stringify(actualPy) !== JSON.stringify(expectedPy);
  for (const [path, content] of expected) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`✗ stale: ${relative(root, path)}`);
      stale = true;
    }
  }
  if (stale) {
    console.error('Package data copies are out of date. Run: npm run sync');
    process.exit(1);
  }
  console.log('✓ Package data copies are up to date');
} else {
  rmSync(pyTarget, { recursive: true, force: true });
  for (const [path, content] of expected) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  console.log(`✓ synced ${sourceFiles.length} data files → Python package + JS generated module`);
}
